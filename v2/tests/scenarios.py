def do(text: str, by: str = "claude-code", name: str = "") -> Dict[str, Any]:
    return {"m": "POST", "p": f"{P}/do?by={by}", "body": text, "name": name or "do " + text.split("\n")[0][:60]}


def get(path: str, name: str = "", **kw: Any) -> Dict[str, Any]:
    return {"m": "GET", "p": path, "name": name, **kw}


def op(body: Any, name: str = "") -> Dict[str, Any]:
    return {"m": "POST", "p": f"{P}/api/op", "body": body, "name": name or f"op {body.get('op') if isinstance(body, dict) else 'batch'}"}


def post(path: str, body: Any, name: str = "", **kw: Any) -> Dict[str, Any]:
    return {"m": "POST", "p": path, "body": body, "name": name or "POST " + path, **kw}


